-- ----------------------------------------------------------------------------
-- 1. USUARIOS Y ROLES
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS usuarios (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(120) NOT NULL,
    email           VARCHAR(160) NOT NULL,
    password_hash   VARCHAR(255) NOT NULL,
    rol             VARCHAR(20)  NOT NULL DEFAULT 'ciudadano'
                    CHECK (rol IN ('admin', 'autoridad', 'ciudadano')),
    organizacion    VARCHAR(160),
    activo          BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_en  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_usuarios_email UNIQUE (email)
);

CREATE INDEX IF NOT EXISTS idx_usuarios_rol ON usuarios (rol, activo);

COMMENT ON TABLE  usuarios IS 'Cuentas de acceso. Sin filas, la app usa las cuentas demo.';
COMMENT ON COLUMN usuarios.password_hash IS 'Hash bcrypt generado con password_hash() de PHP.';
COMMENT ON COLUMN usuarios.activo IS 'FALSE impide el login aunque la contraseña sea correcta.';

-- ----------------------------------------------------------------------------
-- 2. TERRITORIOS
--    Espejo de config/territorios.json. El JSON sigue siendo la fuente del
--    piloto; esta tabla existe para consultas SQL, integridad referencial y
--    para editar el catálogo desde DBeaver.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS territorios (
    id                   VARCHAR(40)  PRIMARY KEY,
    ubigeo               VARCHAR(6),
    pais                 VARCHAR(60)  NOT NULL DEFAULT 'Perú',
    region               VARCHAR(80)  NOT NULL,
    provincia            VARCHAR(80)  NOT NULL,
    distrito             VARCHAR(120) NOT NULL,
    lat                  NUMERIC(9,6) NOT NULL CHECK (lat BETWEEN -90 AND 90),
    lon                  NUMERIC(9,6) NOT NULL CHECK (lon BETWEEN -180 AND 180),
    altitud              SMALLINT     NOT NULL DEFAULT 0,
    zona                 VARCHAR(30)  NOT NULL
                         CHECK (zona IN ('costa_norte', 'costa_centro',
                                         'quebrada_andina', 'sierra', 'selva')),
    poblacion            INTEGER      NOT NULL DEFAULT 0 CHECK (poblacion >= 0),
    viviendas            INTEGER      NOT NULL DEFAULT 0 CHECK (viviendas >= 0),
    escuelas             SMALLINT     NOT NULL DEFAULT 0 CHECK (escuelas >= 0),
    centros_salud        SMALLINT     NOT NULL DEFAULT 0 CHECK (centros_salud >= 0),
    km_vias              NUMERIC(10,2) NOT NULL DEFAULT 0,
    hectareas_cultivo    NUMERIC(10,2) NOT NULL DEFAULT 0,
    vulnerabilidad       NUMERIC(4,3) NOT NULL DEFAULT 0.500
                         CHECK (vulnerabilidad BETWEEN 0 AND 1),
    susc_inundacion      NUMERIC(4,3) NOT NULL DEFAULT 0.000
                         CHECK (susc_inundacion BETWEEN 0 AND 1),
    susc_huaico          NUMERIC(4,3) NOT NULL DEFAULT 0.000
                         CHECK (susc_huaico BETWEEN 0 AND 1),
    susc_sequia          NUMERIC(4,3) NOT NULL DEFAULT 0.000
                         CHECK (susc_sequia BETWEEN 0 AND 1),
    pendiente            NUMERIC(6,2) NOT NULL DEFAULT 0,
    cuenca_km2           NUMERIC(12,2) NOT NULL DEFAULT 0,
    umbral_caudal        NUMERIC(12,2) NOT NULL DEFAULT 0,
    cultivo              VARCHAR(40)  NOT NULL DEFAULT 'ninguno',
    albergues_capacidad  INTEGER      NOT NULL DEFAULT 0 CHECK (albergues_capacidad >= 0),
    fuente_exposicion    VARCHAR(80)  NOT NULL DEFAULT 'estimacion_ratio_poblacional',
    activo               BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_en       TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_territorios_region ON territorios (region);
CREATE INDEX IF NOT EXISTS idx_territorios_zona   ON territorios (zona);
CREATE INDEX IF NOT EXISTS idx_territorios_coord  ON territorios (lat, lon);

COMMENT ON TABLE  territorios IS 'Catálogo piloto de 29 distritos. Población e infraestructura son estimaciones declaradas.';
COMMENT ON COLUMN territorios.fuente_exposicion IS 'Procedencia de los datos de exposición. estimacion_ratio_poblacional = no oficial.';
COMMENT ON COLUMN territorios.susc_inundacion IS 'Susceptibilidad estática 0-1. No es una capa oficial de CENEPRED.';

-- ----------------------------------------------------------------------------
-- 3. ALERTAS / RECOMENDACIONES
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS alertas (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR(40)  NOT NULL,
    territorio_id   VARCHAR(40)  NOT NULL,
    distrito        VARCHAR(120) NOT NULL,
    provincia       VARCHAR(80)  NOT NULL,
    region          VARCHAR(80)  NOT NULL,
    amenaza         VARCHAR(20)  NOT NULL
                    CHECK (amenaza IN ('lluvia', 'inundacion', 'huaico',
                                       'sequia', 'calor', 'agro')),
    nivel           VARCHAR(20)  NOT NULL
                    CHECK (nivel IN ('verde', 'amarillo', 'naranja', 'rojo')),
    titulo          VARCHAR(255) NOT NULL,
    mensaje         TEXT         NOT NULL,
    acciones        JSONB        NOT NULL DEFAULT '[]'::jsonb,
    estado          VARCHAR(20)  NOT NULL DEFAULT 'emitida'
                    CHECK (estado IN ('emitida', 'acusada', 'archivada')),
    emitida_por     VARCHAR(120) NOT NULL DEFAULT 'Sistema',
    emitida_en      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    acuse_por       VARCHAR(120),
    acuse_en        TIMESTAMPTZ,
    nota_legal      VARCHAR(255) NOT NULL DEFAULT
                    'Recomendación de apoyo a la decisión. No reemplaza una alerta oficial de SENAMHI/INDECI/ENFEN.',
    CONSTRAINT uq_alertas_codigo UNIQUE (codigo),
    CONSTRAINT fk_alertas_territorio
        FOREIGN KEY (territorio_id) REFERENCES territorios (id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_alertas_territorio ON alertas (territorio_id, emitida_en DESC);
CREATE INDEX IF NOT EXISTS idx_alertas_nivel      ON alertas (nivel, estado);
CREATE INDEX IF NOT EXISTS idx_alertas_estado     ON alertas (estado, emitida_en DESC);

COMMENT ON TABLE  alertas IS 'Recomendaciones de apoyo a la decisión. NO son alertas oficiales.';
COMMENT ON COLUMN alertas.acciones IS 'Lista JSON de acciones sugeridas según amenaza y nivel.';
COMMENT ON COLUMN alertas.nota_legal IS 'Texto legal que viaja con cada registro.';

-- ----------------------------------------------------------------------------
-- 4. CACHÉ DE GEODATOS
--    Espejo opcional de data/cache/*.json. La app usa archivos por defecto;
--    esta tabla permite auditar respuestas crudas y reconstruir un cálculo.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS cache_geodatos (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave        VARCHAR(255) NOT NULL,
    fuente       VARCHAR(120) NOT NULL DEFAULT 'desconocida',
    payload      JSONB        NOT NULL,
    guardado_en  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expira_en    TIMESTAMPTZ  NOT NULL,
    ttl          INTEGER      NOT NULL DEFAULT 3600 CHECK (ttl >= 0),
    CONSTRAINT uq_cache_clave UNIQUE (clave)
);

CREATE INDEX IF NOT EXISTS idx_cache_expira ON cache_geodatos (expira_en);

COMMENT ON TABLE cache_geodatos IS 'Reservada: espejo opcional de la caché en disco. La app usa hoy los archivos JSON de data/cache/.';

-- ----------------------------------------------------------------------------
-- 5. ESCENARIOS SIMULADOS
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS escenarios (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    territorio_id  VARCHAR(40) NOT NULL,
    modo           VARCHAR(20) NOT NULL
                   CHECK (modo IN ('clima', 'evacuacion', 'reubicacion')),
    parametros     JSONB       NOT NULL,
    resultado      JSONB       NOT NULL,
    creado_por     VARCHAR(120),
    creado_en      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_escenarios_territorio
        FOREIGN KEY (territorio_id) REFERENCES territorios (id)
        ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_escenarios_territorio ON escenarios (territorio_id, creado_en DESC);

COMMENT ON TABLE escenarios IS 'Reservada: auditoría de simulaciones. La app calcula escenarios en memoria; esta tabla las persistirá en la fase 2.';

-- ----------------------------------------------------------------------------
-- 6. AUDITORÍA
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS auditoria (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT,
    accion      VARCHAR(80) NOT NULL,
    entidad     VARCHAR(80),
    entidad_id  VARCHAR(80),
    detalle     JSONB,
    ip          INET,
    creado_en   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_auditoria_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
        ON UPDATE CASCADE ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_auditoria_fecha   ON auditoria (creado_en DESC);
CREATE INDEX IF NOT EXISTS idx_auditoria_usuario ON auditoria (usuario_id);

COMMENT ON TABLE auditoria IS 'Reservada: registro de acciones sensibles (login, emisión, acuse). El módulo de auditoría se activará en la fase 2.';

-- ----------------------------------------------------------------------------
-- 7. TRIGGERS DE actualizado_en
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION willaq_marcar_actualizado()
RETURNS TRIGGER AS $$
BEGIN
    NEW.actualizado_en := now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_usuarios_actualizado ON usuarios;
CREATE TRIGGER trg_usuarios_actualizado
    BEFORE UPDATE ON usuarios
    FOR EACH ROW EXECUTE FUNCTION willaq_marcar_actualizado();

DROP TRIGGER IF EXISTS trg_territorios_actualizado ON territorios;
CREATE TRIGGER trg_territorios_actualizado
    BEFORE UPDATE ON territorios
    FOR EACH ROW EXECUTE FUNCTION willaq_marcar_actualizado();

-- ----------------------------------------------------------------------------
-- 8. VISTAS DE APOYO
-- ----------------------------------------------------------------------------
CREATE OR REPLACE VIEW v_alertas_abiertas AS
SELECT
    codigo,
    territorio_id,
    distrito,
    region,
    amenaza,
    nivel,
    titulo,
    emitida_en,
    estado,
    ROUND(EXTRACT(EPOCH FROM (now() - emitida_en)) / 3600.0, 1) AS horas_desde_emision
FROM alertas
WHERE estado = 'emitida'
ORDER BY emitida_en DESC;

CREATE OR REPLACE VIEW v_resumen_alertas AS
SELECT
    nivel,
    count(*) FILTER (WHERE estado = 'emitida')  AS emitidas,
    count(*) FILTER (WHERE estado = 'acusada')  AS acusadas,
    count(*) FILTER (WHERE estado = 'archivada') AS archivadas,
    count(*) AS total
FROM alertas
GROUP BY nivel
ORDER BY CASE nivel
    WHEN 'rojo'    THEN 1
    WHEN 'naranja' THEN 2
    WHEN 'amarillo' THEN 3
    ELSE 4
END;

